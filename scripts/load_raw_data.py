
"""
Load generated synthetic e-commerce data into PostgreSQL RAW tables.

Input:
    sql/03_insert_raw_data.sql

Configuration:
    DATABASE_URL in the project-root .env file or environment variables.

Safety:
    The generated SQL truncates existing RAW tables before inserting data.
    The script requires explicit confirmation before executing it.

PowerShell examples (from project root):
    python scripts\load_raw_data.py --dry-run
    python scripts\load_raw_data.py
    python scripts\load_raw_data.py --yes
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path
from urllib.parse import urlparse

try:
    import psycopg
except ImportError:
    psycopg = None


# ------------------------------------------------------------
# PROJECT CONFIGURATION
# ------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = PROJECT_ROOT / ".env"
SQL_FILE = PROJECT_ROOT / "sql" / "03_insert_raw_data.sql"

EXPECTED_RAW_TABLES = (
    "customers",
    "products",
    "orders",
    "order_items",
    "payments",
    "shipments",
    "returns",
)


# ------------------------------------------------------------
# ENVIRONMENT CONFIGURATION
# ------------------------------------------------------------

def load_env_file(env_path: Path) -> None:
    """
    Load simple KEY=VALUE entries from .env.

    Existing environment variables take precedence.
    This supports ordinary values and matching surrounding quotes.
    It does not support variable expansion.
    """
    if not env_path.is_file():
        return

    for raw_line in env_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()

        if not line or line.startswith("#"):
            continue

        if line.startswith("export "):
            line = line[len("export "):].strip()

        if "=" not in line:
            continue

        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip()

        if not key:
            continue

        if (
            len(value) >= 2
            and value[0] == value[-1]
            and value[0] in ("'", '"')
        ):
            value = value[1:-1]

        os.environ.setdefault(key, value)


def get_database_url() -> str | None:
    """Read DATABASE_URL from the environment or root .env file."""
    load_env_file(ENV_FILE)

    database_url = os.getenv("DATABASE_URL", "").strip()

    return database_url or None


def safe_connection_summary(database_url: str) -> tuple[str, str]:
    """Return host and database name without exposing the password."""
    parsed = urlparse(database_url)

    host = parsed.hostname or "(host not specified)"
    database = parsed.path.lstrip("/") or "(database not specified)"

    return host, database


# ------------------------------------------------------------
# SQL FILE VALIDATION
# ------------------------------------------------------------

def validate_sql_file(
    sql_path: Path,
) -> tuple[str | None, str | None]:
    """
    Check that the generated SQL file exists and targets RAW tables.

    Returns:
        (sql_text, None) when valid.
        (None, error_message) when invalid.
    """
    if not sql_path.is_file():
        return None, (
            f"SQL file not found: {sql_path}\n"
            "Run python scripts\\generate_raw_data.py first."
        )

    try:
        sql_text = sql_path.read_text(encoding="utf-8-sig")
    except OSError as exc:
        return None, f"Could not read SQL file: {exc}"

    if not sql_text.strip():
        return None, f"SQL file is empty: {sql_path}"

    normalized_sql = sql_text.upper()

    if "TRUNCATE TABLE" not in normalized_sql:
        return None, (
            "The SQL file does not contain the expected TRUNCATE statement. "
            "Check that it was generated by generate_raw_data.py."
        )

    if "RAW." not in normalized_sql:
        return None, (
            "The SQL file does not appear to target the raw schema."
        )

    return sql_text, None


# ------------------------------------------------------------
# SQL PREVIEW
# ------------------------------------------------------------

def count_insert_statements(sql_text: str) -> dict[str, int]:
    """Count generated INSERT statements by RAW table."""
    counts = {table: 0 for table in EXPECTED_RAW_TABLES}

    for line in sql_text.splitlines():
        stripped = line.strip()

        if not stripped.upper().startswith("INSERT INTO RAW."):
            continue

        remainder = stripped[len("INSERT INTO raw."):]
        table_name = (
            remainder.split(None, 1)[0]
            .split("(", 1)[0]
            .lower()
        )

        if table_name in counts:
            counts[table_name] += 1

    return counts


def print_preview(sql_text: str) -> None:
    """Display the SQL file and expected insert counts."""
    counts = count_insert_statements(sql_text)

    print("\nGenerated SQL preview")
    print("=" * 40)
    print(f"SQL file: {SQL_FILE}")
    print("Target schema: raw")
    print("Operation: TRUNCATE existing tables, then INSERT generated rows")
    print("\nINSERT statements by table:")

    for table_name in EXPECTED_RAW_TABLES:
        print(f"  raw.{table_name:<12} {counts[table_name]:>5}")

    print(f"  {'TOTAL':<16} {sum(counts.values()):>5}")
    print("\nPreview only: no database changes have been made.")


# ------------------------------------------------------------
# DATABASE VALIDATION
# ------------------------------------------------------------

def check_required_tables(connection) -> list[str]:
    """Return expected RAW tables that do not exist."""
    with connection.cursor() as cursor:
        cursor.execute(
            """
            SELECT table_name
            FROM information_schema.tables
            WHERE table_schema = 'raw'
              AND table_type = 'BASE TABLE'
            """
        )

        existing_tables = {
            row[0] for row in cursor.fetchall()
        }

    return [
        table_name
        for table_name in EXPECTED_RAW_TABLES
        if table_name not in existing_tables
    ]


# ------------------------------------------------------------
# LOAD DATA
# ------------------------------------------------------------

def load_data(database_url: str, sql_text: str) -> bool:
    """Execute the generated SQL script against PostgreSQL."""
    if psycopg is None:
        print("ERROR: psycopg is not installed.")
        print('Install it with: python -m pip install "psycopg[binary]"')
        return False

    host, database = safe_connection_summary(database_url)

    print("\nPostgreSQL RAW data loader")
    print("=" * 40)
    print(f"Host: {host}")
    print(f"Database: {database}")
    print(f"SQL file: {SQL_FILE}")

    try:
        # psycopg's connection context rolls back an open transaction
        # on exceptions and closes the connection when finished.
        with psycopg.connect(
            database_url,
            connect_timeout=8,
            application_name="ecommerce_analytics_raw_loader",
        ) as connection:

            missing_tables = check_required_tables(connection)

            if missing_tables:
                print("\nERROR: Required RAW tables are missing:")

                for table_name in missing_tables:
                    print(f"  - raw.{table_name}")

                print(
                    "\nCreate the RAW schema and tables before loading data."
                )
                return False

            print("\nAll required RAW tables are present.")
            print("Executing generated SQL...")

            # The generated script contains multiple SQL statements.
            # prepare=False uses psycopg 3's simple-query protocol.
            with connection.cursor() as cursor:
                cursor.execute(sql_text, prepare=False)

            print("\nLOAD SUCCESSFUL")
            print("Generated SQL executed successfully.")
            print("\nFinal RAW table row counts:")

            with connection.cursor() as cursor:
                for table_name in EXPECTED_RAW_TABLES:
                    # Table names come exclusively from the constant list.
                    cursor.execute(
                        f"SELECT COUNT(*) FROM raw.{table_name}"
                    )
                    row_count = cursor.fetchone()[0]

                    print(f"  raw.{table_name:<12} {row_count:>5}")

            return True

    except Exception as exc:
        print("\nLOAD FAILED")
        print(f"Error type: {type(exc).__name__}")
        print(f"Error: {exc}")
        print(
            "\nReview the SQL error, source table definitions, "
            "database settings, and permissions."
        )

        return False


# ------------------------------------------------------------
# COMMAND-LINE ARGUMENTS
# ------------------------------------------------------------

def parse_args() -> argparse.Namespace:
    """Parse supported command-line options."""
    parser = argparse.ArgumentParser(
        description=(
            "Load generated e-commerce data into PostgreSQL RAW tables. "
            "This replaces existing RAW data."
        )
    )

    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview the generated SQL without connecting to PostgreSQL.",
    )

    parser.add_argument(
        "--yes",
        action="store_true",
        help=(
            "Confirm replacement of existing RAW data without an "
            "interactive prompt."
        ),
    )

    return parser.parse_args()


# ------------------------------------------------------------
# MAIN ENTRY POINT
# ------------------------------------------------------------

def main() -> int:
    """Run validation and load data when explicitly confirmed."""
    args = parse_args()

    sql_text, error = validate_sql_file(SQL_FILE)

    if error:
        print(f"ERROR: {error}")
        return 2

    assert sql_text is not None

    print_preview(sql_text)

    if args.dry_run:
        return 0

    database_url = get_database_url()

    if not database_url:
        print("\nERROR: DATABASE_URL is not set.")
        print(f"Expected .env location: {ENV_FILE}")
        print(
            "Set DATABASE_URL in .env or in your environment. "
            "Never commit .env to Git."
        )
        return 2

    if not args.yes:
        print("\nWARNING: DESTRUCTIVE OPERATION")
        print(
            "This will truncate and reload the existing RAW tables."
        )

        confirmation = input(
            "Type LOAD RAW DATA to continue, or press Enter to cancel: "
        ).strip()

        if confirmation != "LOAD RAW DATA":
            print("Cancelled. No data was loaded.")
            return 0

    success = load_data(database_url, sql_text)

    return 0 if success else 1


if __name__ == "__main__":
    sys.exit(main())
