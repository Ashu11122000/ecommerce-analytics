
-- ============================================================
-- Model: fact_payments
-- Layer: Gold
-- Purpose:
--   Create an analytics-ready payment fact table for monitoring
--   payment amounts, payment success, payment methods, and
--   payment processing data quality.
--
-- Grain:
--   One row per payment (payment_id).
--
-- Source:
--   silver_payments
--
-- Important assumptions:
--   1. Each payment_id identifies one payment record.
--   2. Payment amounts use the currency associated with the
--      relevant order; amounts across currencies must not be
--      aggregated without conversion.
--   3. Payment success is based on the standardized payment
--      status defined in the Silver model.
--   4. payment_update_delay_days measures calendar days between
--      payment_date and updated_at.
-- ============================================================

WITH payments_base AS (

    -- Step 1: Select enriched payment records from Silver.
    SELECT
        payment_id,
        order_id,
        payment_date,
        payment_method,
        payment_status,
        payment_status_group,
        amount,
        is_successful_payment,
        has_transaction_reference,
        payment_amount_band,
        payment_update_delay_days,
        updated_at,
        ingested_at,
        loaded_at,
        transformed_at

    FROM {{ ref('silver_payments') }}

),

payments_prepared AS (

    -- Step 2: Add the date dimension key.
    SELECT
        *,

        -- Create an integer date key in YYYYMMDD format.
        -- Example: 20261027 represents October 27, 2026.
        -- Preserve NULL if the payment date is missing.
        CASE
            WHEN payment_date IS NOT NULL
            THEN TO_CHAR(payment_date::DATE, 'YYYYMMDD')::INTEGER
            ELSE NULL
        END AS payment_date_key

    FROM payments_base

)

-- Step 3: Return the final Gold payment fact table.
SELECT
    -- Payment fact key.
    payment_id,

    -- Foreign keys for analysis and filtering.
    order_id,
    payment_date_key,

    -- Payment descriptive attributes.
    payment_method,
    payment_status,
    payment_status_group,

    -- Payment measure.
    amount,

    -- Analytical indicators.
    is_successful_payment,
    has_transaction_reference,

    -- Payment amount classification.
    payment_amount_band,

    -- Operational monitoring metric.
    payment_update_delay_days,

    -- Technical lineage timestamps.
    updated_at,
    ingested_at,
    loaded_at,
    transformed_at,

    -- Timestamp generated by the modeled_timestamp macro.
    -- Actual behavior depends on the macro implementation.
    {{ modeled_timestamp() }} AS modeled_at

FROM payments_prepared
