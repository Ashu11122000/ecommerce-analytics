
{#
    Macro: generate_schema_name

    Purpose:
    - Control the database schema name generated by dbt.
    - Support separate Bronze, Silver, and Gold schemas.
    - Keep schema naming predictable across environments.

    Behavior:
    - If a custom schema is configured, use that schema name.
    - Otherwise, use the target schema from the active dbt profile.

    Important:
    - This overrides dbt's default schema naming behavior.
    - Verify the resulting schemas before running production models.
#}

{% macro generate_schema_name(custom_schema_name, node) -%}

    {%- if custom_schema_name is not none -%}
        {{ custom_schema_name | trim }}
    {%- else -%}
        {{ target.schema }}
    {%- endif -%}

{%- endmacro %}
